class LessonRepository {
  final SupabaseClient? _client;

  LessonRepository(this._client);

  Future<List<Lesson>> getLessons() async {
    if (_client == null) {
      final mocks = _getMockLessons();
      await LocalCacheService.saveLessons(mocks);
      return mocks;
    }

    final cached = LocalCacheService.getCachedLessons();
    if (cached.isNotEmpty) {
      return cached;
    }

    try {
      final response = await _client
          .from('lessons')
          .select()
          .order('created_at', ascending: true);
      final lessons = (response as List)
          .map((json) => Lesson.fromJson(json as Map<String, dynamic>))
          .toList();
      await LocalCacheService.saveLessons(lessons);
      return lessons;
    } catch (e) {
      final mocks = _getMockLessons();
      await LocalCacheService.saveLessons(mocks);
      return mocks;
    }
  }

  Future<List<Lesson>> getLessonsByDifficulty(String difficulty) async {
    final allLessons = await getLessons();
    final filtered = allLessons
        .where((l) => l.difficulty == difficulty.toLowerCase())
        .toList();
    if (filtered.isNotEmpty) {
      return filtered;
    }

    if (_client == null) {
      return _getMockLessons()
          .where((l) => l.difficulty == difficulty.toLowerCase())
          .toList();
    }
    try {
      final response = await _client
          .from('lessons')
          .select()
          .eq('difficulty', difficulty.toLowerCase());
      return (response as List)
          .map((json) => Lesson.fromJson(json as Map<String, dynamic>))
          .toList();
    } catch (e) {
      return _getMockLessons()
          .where((l) => l.difficulty == difficulty.toLowerCase())
          .toList();
    }
  }

